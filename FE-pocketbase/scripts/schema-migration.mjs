// Turns src/setup/collections.json into append-only PocketBase JS migrations.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const MIGRATION_SUFFIX = "_aura_collections.js";

const timestampOf = (fileName) => Number.parseInt(fileName, 10);

export const renderMigration = (collections, { first }) => {
  // Double-encoding yields a plain JS string literal: no template-literal escaping pitfalls.
  const literal = JSON.stringify(JSON.stringify(collections));
  const names = JSON.stringify(collections.map((c) => c.name).reverse());
  const down = first
    ? `(app) => {
  for (const name of ${names}) {
    try {
      app.delete(app.findCollectionByNameOrId(name));
    } catch (_) {
      // Already gone.
    }
  }
}`
    : `(app) => {
  // Schema updates are not reverted automatically; restore from a backup if needed.
}`;

  return `/// <reference path="../pb_data/types.d.ts" />
// Generated by FE-pocketbase/scripts/sync-schema.mjs from FE-pocketbase/src/setup/collections.json.
// Do not edit. Change the JSON and run \`bun run sync:schema\` to append a new migration.
migrate((app) => {
  app.importCollectionsByMarshaledJSON(${literal}, false);
}, ${down});
`;
};

export const extractCollections = (source) => {
  const match = source.match(/importCollectionsByMarshaledJSON\(("(?:[^"\\]|\\.)*"), false\)/);
  if (!match) return null;
  return JSON.parse(JSON.parse(match[1]));
};

export const latestMigration = (fileNames) =>
  fileNames
    .filter((name) => name.endsWith(MIGRATION_SUFFIX) && Number.isFinite(timestampOf(name)))
    .sort((a, b) => timestampOf(a) - timestampOf(b))
    .at(-1) ?? null;

export const syncSchema = ({ collections, migrationsDir, now, check }) => {
  const latest = latestMigration(readdirSync(migrationsDir));
  if (latest) {
    const current = extractCollections(readFileSync(join(migrationsDir, latest), "utf8"));
    if (JSON.stringify(current) === JSON.stringify(collections)) {
      return { status: "up-to-date", file: latest };
    }
  }
  if (check) return { status: "outdated", file: null };

  const file = `${Math.floor(now / 1000)}${MIGRATION_SUFFIX}`;
  writeFileSync(join(migrationsDir, file), renderMigration(collections, { first: latest === null }));
  return { status: "written", file };
};
